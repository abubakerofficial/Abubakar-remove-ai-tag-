test('validateVideoFile rejects empty or oversized or non-media files', () => {
  const emptyRes = validateVideoFile('clip.mp4', 0, 'video/mp4');
  assert.equal(emptyRes.valid, false);
  assert.match(emptyRes.error || '', /empty/i);

  const hugeRes = validateVideoFile('clip.mp4', 600 * 1024 * 1024, 'video/mp4');
  assert.equal(hugeRes.valid, false);
  assert.match(hugeRes.error || '', /500 MB/i);

  const badType = validateVideoFile('document.pdf', 2048, 'application/pdf');
  assert.equal(badType.valid, false);
  assert.match(badType.error || '', /Unsupported format/i);
});

