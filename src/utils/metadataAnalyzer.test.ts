import test from 'node:test';
import assert from 'node:assert/strict';
import {
  validateVideoFile,
  formatBytes,
  inspectBinaryForAiMetadata,
  buildFfmpegCommandString,
  FFMPEG_LOSSLESS_ARGS,
  stripMp4MetadataInBrowser,
  createBrowserSampleMp4Buffer,
} from './metadataAnalyzer';

test('validateVideoFile accepts valid MP4 files and automatically renames to Abubakar Remove AI.mp4', () => {
  const res = validateVideoFile('Runway_Gen3_Scene 01.mp4', 12_500_000, 'video/mp4');
  assert.equal(res.valid, true);
  assert.equal(res.normalizedCleanName, 'Abubakar Remove AI.mp4');
});

test('validateVideoFile rejects empty or oversized or non-video files', () => {
  const emptyRes = validateVideoFile('clip.mp4', 0, 'video/mp4');
  assert.equal(emptyRes.valid, false);
  assert.match(emptyRes.error || '', /empty/i);

  const hugeRes = validateVideoFile('clip.mp4', 600 * 1024 * 1024, 'video/mp4');
  assert.equal(hugeRes.valid, false);
  assert.match(hugeRes.error || '', /500 MB/i);

  const badType = validateVideoFile('document.pdf', 2048, 'application/pdf');
  assert.equal(badType.valid, false);
  assert.match(badType.error || '', /Unsupported format/i);
});

test('formatBytes formats byte counts cleanly with tabular precision', () => {
  assert.equal(formatBytes(0), '0 B');
  assert.equal(formatBytes(512), '512 B');
  assert.equal(formatBytes(1024 * 1024 * 4.5), '4.50 MB');
});

test('inspectBinaryForAiMetadata detects Google Flow, Runway, Luma, Pika, and C2PA signatures', () => {
  const encoder = new TextEncoder();
  const simulatedMp4Bytes = encoder.encode(
    'ftypisom...moov...udta...Generated by Google Flow and Runway Gen-3 with Luma Dream Machine Pika c2pa.jumbf'
  );
  const tags = inspectBinaryForAiMetadata(simulatedMp4Bytes, 'ai_render.mp4');
  const platforms = tags.map((t) => t.platform);
  assert.ok(platforms.includes('Google Flow'));
  assert.ok(platforms.includes('Runway'));
  assert.ok(platforms.includes('Luma'));
  assert.ok(platforms.includes('Pika'));
  assert.ok(platforms.includes('C2PA / EXIF'));
});

test('buildFfmpegCommandString includes lossless stream copy and metadata strip flags', () => {
  const cmd = buildFfmpegCommandString('input.mp4', 'clean.mp4');
  assert.ok(cmd.includes('-map_metadata -1'));
  assert.ok(cmd.includes('-c:v copy'));
  assert.ok(cmd.includes('-c:a copy'));
  assert.ok(FFMPEG_LOSSLESS_ARGS.includes('-map_metadata'));
});

test('stripMp4MetadataInBrowser removes all AI signatures from sample MP4 buffer for static hosting', () => {
  const sampleBuf = createBrowserSampleMp4Buffer('runway');
  const beforeTags = inspectBinaryForAiMetadata(sampleBuf, 'sample.mp4');
  assert.equal(beforeTags.length, 6);

  const cleanedBuf = stripMp4MetadataInBrowser(sampleBuf);
  const decoder = new TextDecoder('latin1');
  const cleanedText = decoder.decode(cleanedBuf);
  assert.equal(/Runway|Google Flow|Luma|Pika|c2pa/i.test(cleanedText), false);
});

test('stripMp4MetadataInBrowser parses real MP4 box tree, converts udta/uuid to free, and preserves mdat bytes', () => {
  const makeBox = (type: string, payload: Uint8Array): Uint8Array => {
    const size = 8 + payload.byteLength;
    const out = new Uint8Array(size);
    out[0] = (size >>> 24) & 0xff;
    out[1] = (size >>> 16) & 0xff;
    out[2] = (size >>> 8) & 0xff;
    out[3] = size & 0xff;
    for (let i = 0; i < 4; i++) out[4 + i] = type.charCodeAt(i);
    out.set(payload, 8);
    return out;
  };

  const enc = new TextEncoder();
  const ftyp = makeBox('ftyp', enc.encode('isom0000isommp42'));
  const mvhd = makeBox('mvhd', new Uint8Array([1, 2, 3, 4, 5, 6, 7, 8]));
  const udta = makeBox('udta', enc.encode('Runway Gen-3 Alpha | Google Flow | Luma | Pika'));
  const moovPayload = new Uint8Array(mvhd.byteLength + udta.byteLength);
  moovPayload.set(mvhd, 0);
  moovPayload.set(udta, mvhd.byteLength);
  const moov = makeBox('moov', moovPayload);
  const uuid = makeBox('uuid', enc.encode('c2pa.jumbf.manifest TrainedAlgorithmicMedia'));
  const mdatPayload = enc.encode('RAW_VIDEO_FRAME_BYTES_Runway_SHOULD_NOT_BE_TOUCHED');
  const mdat = makeBox('mdat', mdatPayload);

  const mp4 = new Uint8Array(
    ftyp.byteLength + moov.byteLength + uuid.byteLength + mdat.byteLength
  );
  let pos = 0;
  for (const part of [ftyp, moov, uuid, mdat]) {
    mp4.set(part, pos);
    pos += part.byteLength;
  }

  const scrubbed = stripMp4MetadataInBrowser(mp4);
  assert.equal(scrubbed.byteLength, mp4.byteLength);

  const dec = new TextDecoder('latin1');
  const beforeMdatText = dec.decode(
    scrubbed.subarray(0, ftyp.byteLength + moov.byteLength + uuid.byteLength)
  );
  assert.equal(/Runway|Google Flow|Luma|Pika|c2pa/i.test(beforeMdatText), false);

  // Verify mdat payload is 100% bit-exact untouched
  const mdatSlice = scrubbed.subarray(
    mp4.byteLength - mdatPayload.byteLength,
    mp4.byteLength
  );
  assert.equal(dec.decode(mdatSlice), 'RAW_VIDEO_FRAME_BYTES_Runway_SHOULD_NOT_BE_TOUCHED');
});


